def self_check():
    gt = action_rgb(np.array([[0.3, -0.2], [-0.1, 0.4]], dtype=np.float32).astype(np.float64))
    pred = action_rgb(np.array([[0.2, -0.1], [-0.2, 0.2]], dtype=np.float64))
    recovery, reproduction = independent_errors(pred, gt)
    require(np.isfinite(recovery).all() and np.isfinite(reproduction).all(), "Angle self-check failed")
    exact_recovery, exact_reproduction = independent_errors(gt, gt)
    close(exact_recovery, np.zeros_like(exact_recovery), "exact recovery", atol=1e-12)
    close(exact_reproduction, np.zeros_like(exact_reproduction), "exact reproduction", atol=1e-12)
    point = np.array([[0.0, 0.0], [0.1, -0.2]], dtype=np.float32)
    trajectory = np.repeat(point[:, None, :], 4, axis=1)
    oracle = reconstruct_oracles(point, trajectory, gt)
    require(set(oracle) == set(STAGES), "Oracle stages missing")
    require(all(values.shape == (2,) for values in oracle.values()), "Oracle shape failed")
    curve = independent_risk_curve(np.array([3.0, 1.0, 2.0]), np.array([0.2, 0.1, 0.3]), ["a", "b", "c"])
    close(curve["mean_reproduction"], [1.0, 2.0, 2.0], "risk ordering")
    return {"status": "passed", "checks": ["atan2 exact null", "action-grid oracle", "stable risk coverage"]}


