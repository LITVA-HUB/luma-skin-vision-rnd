def validate_benchmark_receipt(mode, run, config, result, path):
    receipt = read_json(path)
    require(receipt["schema"] == "cc-v4-batch1-inference-1", f"{mode}: benchmark schema changed")
    require(receipt["mode"] == mode, f"{mode}: benchmark mode mismatch")
    require(receipt["is_frozen_primary"] is True and receipt["training_status"] == "complete", f"{mode}: benchmark is not a completed primary run")
    require(Path(receipt["run"]).resolve() == run.resolve(), f"{mode}: benchmark run mismatch")
    require(receipt["config_sha256"] == sha256(run / "config.json"), f"{mode}: benchmark config mismatch")
    require(receipt["run_manifest_sha256"] == sha256(run / "artifact_manifest.json"), f"{mode}: benchmark manifest mismatch")
    require(receipt["checkpoint_sha256"] == sha256(run / "best.pt"), f"{mode}: benchmark checkpoint mismatch")
    require(receipt["decoder_sha256"] == config["scripts_sha256"]["cc_v2_statistics.py"], f"{mode}: benchmark decoder mismatch")
    require(receipt["model_sha256"] == config["scripts_sha256"]["cc_v4_model.py"], f"{mode}: benchmark model mismatch")
    require(receipt["parameters"] == result["parameters"], f"{mode}: benchmark parameter mismatch")
    require(receipt["repeats_per_stage"] >= 100, f"{mode}: definitive benchmark needs >=100 repetitions")
    for stage, queries in ((1, 25), (2, 51), (4, 103)):
        values = receipt["stages"][str(stage)]
        require(values["observed_queries"] == [queries], f"{mode}: stage{stage} query count changed")
        require(len(values["samples_ms"]) == receipt["repeats_per_stage"], f"{mode}: incomplete timing samples")
        close(np.median(values["samples_ms"]), values["median_ms"], f"{mode}.benchmark.stage{stage}.median")
        close(np.percentile(values["samples_ms"], 95), values["p95_ms"], f"{mode}.benchmark.stage{stage}.p95")
    return {**receipt, "receipt_file": path.name, "receipt_sha256": sha256(path)}


def validate_benchmarks(mode, run, config, result):
    primary = ROOT / f"experiments/runs/{RUN_NAMES[mode]}_benchmark.json"
    if not primary.exists():
        return {"status": "PENDING", "reason": "Definitive uncontended 100-repeat benchmark receipt is missing"}, []
    paths = [primary]
    paths.extend(
        path for path in (
            ROOT / f"experiments/runs/{RUN_NAMES[mode]}_benchmark_repeat2.json",
            ROOT / f"experiments/runs/{RUN_NAMES[mode]}_benchmark_repeat3.json",
        )
        if path.exists()
    )
    receipts = [validate_benchmark_receipt(mode, run, config, result, path) for path in paths]
    median_range = {
        str(stage): [
            float(min(receipt["stages"][str(stage)]["median_ms"] for receipt in receipts)),
            float(max(receipt["stages"][str(stage)]["median_ms"] for receipt in receipts)),
        ]
        for stage in STAGES
    }
    return {**receipts[0], "status": "MEASURED", "replicates": receipts, "median_range_ms": median_range}, paths


def validate_roles(configs):
    rows = read_json(DATA / "cube_manifest.json")
    require(len(rows) == 2234, "Source manifest row count changed")
    by_id = {row["id"]: (i, row) for i, row in enumerate(rows)}
    require(len(by_id) == len(rows), "Source manifest IDs are not unique")
    config = configs[MODES[0]]
    train, validation = config["train_ids"], config["validation_ids"]
    require((len(train), len(validation)) == (1126, 119), "Frozen role counts changed")
    require(set(train).isdisjoint(validation), "Train/validation IDs overlap")
    require(all(by_id[x][1]["subset"] == "train" for x in train), "Recorded train role changed")
    require(all(by_id[x][1]["subset"] == "val" for x in validation), "Recorded validation role changed")
    train_groups = {by_id[x][1]["group"] for x in train}
    val_groups = {by_id[x][1]["group"] for x in validation}
    require(train_groups.isdisjoint(val_groups), "Train/validation capture groups overlap")
    indices = np.array([by_id[x][0] for x in validation], dtype=np.int64)
    require(np.all(indices[1:] > indices[:-1]), "Validation IDs are not in immutable source order")
    # Recreate runner behavior: source GT first becomes float32, then audit geometry in float64.
    gt = read_npz_rows(DATA / "cube.npz", "gt", indices, expected_rows=2234).astype(np.float32).astype(np.float64)
    require(np.isfinite(gt).all() and np.all(gt > 0), "Invalid source-validation illuminant GT")
    return rows, gt, train_groups, val_groups


