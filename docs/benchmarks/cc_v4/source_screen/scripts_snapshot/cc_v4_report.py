def require(condition, message):
    if not condition:
        raise ValueError(message)


def safe_report_child(path, prefix, *, must_exist):
    """Resolve and constrain every report-directory move/delete on Windows."""
    path = Path(path)
    workspace = ROOT.resolve()
    parent = REPORT_PARENT.resolve()
    require(parent.is_relative_to(workspace), "Report parent escaped the repository")
    require(path.parent.resolve() == parent, f"Unsafe report path parent: {path}")
    require(path.name.startswith(prefix), f"Unsafe report path name: {path.name}")
    exists = path.exists()
    require(exists == must_exist, f"Unexpected report path existence: {path}")
    if exists:
        is_junction = getattr(path, "is_junction", lambda: False)()
        require(not path.is_symlink() and not is_junction, f"Refuse linked report directory: {path}")
        require(path.resolve().parent == parent, f"Resolved report path escaped parent: {path}")
        require(path.is_dir(), f"Expected report directory: {path}")
    else:
        require(path.resolve().parent == parent, f"Prospective report path escaped parent: {path}")
    return path


def close(actual, expected, label, atol=1e-6):
    a, b = np.asarray(actual), np.asarray(expected)
    if a.shape != b.shape or not np.allclose(a, b, rtol=0, atol=atol):
        defect = np.inf if a.shape != b.shape else float(np.max(np.abs(a - b)))
        raise ValueError(f"{label} differs (max defect {defect})")


def independent_summary(values):
    ordered = np.sort(np.asarray(values, dtype=np.float64))
    require(ordered.ndim == 1 and len(ordered) > 0, "Summary needs a nonempty vector")
    require(np.isfinite(ordered).all() and np.all(ordered >= -1e-9), "Invalid summary values")
    q1, median, q3 = np.percentile(ordered, (25, 50, 75))
    tail = max(1, int(np.ceil(len(ordered) / 4)))
    return {
        "n": len(ordered),
        "mean": float(ordered.mean()),
        "median": float(median),
        "trimean": float((q1 + 2 * median + q3) / 4),
        "best25": float(ordered[:tail].mean()),
        "worst25": float(ordered[-tail:].mean()),
        "p90": float(np.percentile(ordered, 90)),
        "p95": float(np.percentile(ordered, 95)),
        "max": float(ordered[-1]),
        "over10_fraction": float(np.mean(ordered > 10)),
        "over20_fraction": float(np.mean(ordered > 20)),
    }


def validate_summary(actual, expected, label):
    require(set(actual) == set(expected), f"{label} summary fields changed")
    for key in actual:
        close(actual[key], expected[key], f"{label}.{key}")


def action_rgb(actions):
    actions = np.asarray(actions, dtype=np.float64)
    require(actions.shape[-1] == 2 and np.isfinite(actions).all(), "Invalid saved actions")
    logs = np.stack((actions[..., 0], np.zeros(actions.shape[:-1]), actions[..., 1]), axis=-1)
    rgb = np.exp(logs - logs.max(axis=-1, keepdims=True))
    return rgb / np.linalg.norm(rgb, axis=-1, keepdims=True)


def independent_errors(prediction, ground_truth):
    pred = np.asarray(prediction, dtype=np.float64)
    gt = np.asarray(ground_truth, dtype=np.float64)
    require(pred.shape == gt.shape and pred.shape[-1] == 3, "Prediction/GT shape mismatch")
    require(np.isfinite(pred).all() and np.isfinite(gt).all(), "Nonfinite prediction/GT")
    require(np.all(pred > 0) and np.all(gt > 0), "Angles require positive prediction/GT")
    recovery = np.degrees(
        np.arctan2(np.linalg.norm(np.cross(pred, gt), axis=-1), np.sum(pred * gt, axis=-1))
    )
    residual = gt / pred
    neutral = np.ones_like(residual)
    reproduction = np.degrees(
        np.arctan2(
            np.linalg.norm(np.cross(residual, neutral), axis=-1),
            np.sum(residual * neutral, axis=-1),
        )
    )
    return recovery, reproduction


def independent_risk_curve(errors, risk, ids):
    errors, risk = np.asarray(errors, dtype=np.float64), np.asarray(risk, dtype=np.float64)
    require(errors.shape == risk.shape == (len(ids),), "Risk inputs are not aligned")
    require(np.isfinite(errors).all() and np.isfinite(risk).all(), "Nonfinite risk inputs")
    order = np.argsort(risk, kind="stable")
    ranked = errors[order]
    means = np.cumsum(ranked) / np.arange(1, len(ranked) + 1)
    fixed = {}
    for percent in FIXED_COVERAGE:
        n = max(1, int(np.floor(len(ranked) * percent / 100)))
        fixed[str(percent)] = {
            **independent_summary(ranked[:n]),
            "accepted": n,
            "coverage": n / len(ranked),
            "over10": int(np.sum(ranked[:n] > 10)),
        }
    return {
        "fixed": fixed,
        "coverage": (np.arange(1, len(ranked) + 1) / len(ranked)).tolist(),
        "mean_reproduction": means.tolist(),
        "aurc_discrete_mean": float(means.mean()),
        "order": order.tolist(),
        "ordered_ids": [ids[i] for i in order],
        "status": "Raw model ranking on reused development validation; uncalibrated",
    }


def validate_runner_risk(rebuilt, reported, label):
    close(rebuilt["mean_reproduction"], reported["curve"], f"{label}.curve")
    close(rebuilt["aurc_discrete_mean"], reported["aurc_discrete_mean"], f"{label}.aurc")
    for percent in FIXED_COVERAGE:
        ours, theirs = rebuilt["fixed"][str(percent)], reported["fixed"][str(percent)]
        for key in ("accepted", "coverage", "mean", "p95", "over10"):
            close(ours[key], theirs[key], f"{label}.{percent}.{key}")


def reconstruct_oracles(point_action, trajectory_actions, ground_truth):
    point = np.asarray(point_action, dtype=np.float64)
    trajectory = np.asarray(trajectory_actions, dtype=np.float64)
    require(point.shape == (len(ground_truth), 2), "Point-action shape changed")
    require(trajectory.shape == (len(ground_truth), 4, 2), "Trajectory shape changed")
    axis = np.linspace(-1, 1, 5)
    offsets = np.array([(x, y) for x in axis for y in axis], dtype=np.float64)
    cumulative, oracle = [], {}
    for index, radius in enumerate(RADII):
        center = point if index == 0 else trajectory[:, index - 1]
        grid = np.clip(center[:, None, :] + radius * offsets[None, :, :], -2, 2)
        cumulative.append(grid)
        if index:
            cumulative.append(point[:, None, :])
        candidates = np.concatenate(cumulative, axis=1)
        if index + 1 in STAGES:
            pred = action_rgb(candidates)
            gt = np.broadcast_to(ground_truth[:, None, :], pred.shape)
            _, error = independent_errors(pred.reshape(-1, 3), gt.reshape(-1, 3))
            oracle[index + 1] = error.reshape(len(point), -1).min(axis=1)
            require(candidates.shape[1] == {1: 25, 2: 51, 4: 103}[index + 1], f"Stage-{index + 1} candidate budget changed")
    return oracle


def load_npz(path):
    with np.load(path, allow_pickle=False) as archive:
        return {name: archive[name] for name in archive.files}


def validate_archive(arrays, metrics, ground_truth, ids, label):
    required = {
        "point_action", "trajectory_actions", "trajectory_risk", "valid", "base_pred",
        "base_reproduction", "trajectory_reproduction", "trajectory_recovery", "oracle2",
        "oracle4", "pred", "reproduction", "risk",
    }
    require(set(arrays) == required, f"{label}: validation NPZ fields changed")
    n = len(ids)
    require(arrays["valid"].shape == (n,), f"{label}: valid shape changed")
    require(arrays["valid"].dtype == np.bool_, f"{label}: valid dtype changed")
    require(arrays["valid"].all(), f"{label}: unsupported validation rows require an input audit")
    point_pred = action_rgb(arrays["point_action"].astype(np.float64))
    trajectory_pred = action_rgb(arrays["trajectory_actions"].astype(np.float64))
    close(point_pred, arrays["base_pred"], f"{label}.base_pred")
    close(trajectory_pred[:, 1], arrays["pred"], f"{label}.pred")
    close(arrays["trajectory_risk"][:, 1], arrays["risk"], f"{label}.risk")
    point_recovery, point_reproduction = independent_errors(point_pred, ground_truth)
    close(point_reproduction, arrays["base_reproduction"], f"{label}.base_reproduction")
    trajectory_recovery, trajectory_reproduction = [], []
    for step in range(4):
        recovery, reproduction = independent_errors(trajectory_pred[:, step], ground_truth)
        trajectory_recovery.append(recovery)
        trajectory_reproduction.append(reproduction)
    trajectory_recovery = np.stack(trajectory_recovery, axis=1)
    trajectory_reproduction = np.stack(trajectory_reproduction, axis=1)
    close(trajectory_recovery, arrays["trajectory_recovery"], f"{label}.trajectory_recovery")
    close(trajectory_reproduction, arrays["trajectory_reproduction"], f"{label}.trajectory_reproduction")
    close(trajectory_reproduction[:, 1], arrays["reproduction"], f"{label}.reproduction")
    validate_summary(independent_summary(point_reproduction), metrics["base_reproduction"], f"{label}.base")
    require(metrics["observed_four_stage_queries"] == [103], f"{label}: query receipt changed")
    require(abs(metrics["valid_fraction"] - 1.0) <= 1e-12, f"{label}: invalid validation row")
    risk_curves, stage_summaries = {}, {}
    for stage in STAGES:
        index = stage - 1
        repro_summary = independent_summary(trajectory_reproduction[:, index])
        recovery_summary = independent_summary(trajectory_recovery[:, index])
        validate_summary(repro_summary, metrics["stages"][str(stage)]["reproduction"], f"{label}.stage{stage}.repro")
        validate_summary(recovery_summary, metrics["stages"][str(stage)]["recovery"], f"{label}.stage{stage}.recovery")
        curve = independent_risk_curve(trajectory_reproduction[:, index], arrays["trajectory_risk"][:, index], ids)
        validate_runner_risk(curve, metrics["stages"][str(stage)]["risk"], f"{label}.stage{stage}.risk")
        risk_curves[str(stage)] = curve
        delta = trajectory_reproduction[:, index] - point_reproduction
        stage_summaries[str(stage)] = {
            "reproduction": repro_summary,
            "recovery": recovery_summary,
            "worsened_vs_direct_point": int(np.sum(delta > 1e-6)),
            "worsened_vs_direct_point_fraction": float(np.mean(delta > 1e-6)),
            "improved_vs_direct_point": int(np.sum(delta < -1e-6)),
            "mean_delta_vs_direct_point": float(delta.mean()),
        }
    oracles = reconstruct_oracles(arrays["point_action"], arrays["trajectory_actions"], ground_truth)
    close(oracles[2], arrays["oracle2"], f"{label}.oracle2")
    close(oracles[4], arrays["oracle4"], f"{label}.oracle4")
    close(oracles[2].mean(), metrics["oracle2_mean"], f"{label}.oracle2_mean")
    close(oracles[4].mean(), metrics["oracle4_mean"], f"{label}.oracle4_mean")
    oracle_output, per_image = {}, []
    for stage in STAGES:
        selected = trajectory_reproduction[:, stage - 1]
        regret = selected - oracles[stage]
        require(np.min(regret) >= -1e-6, f"{label}: selected stage{stage} action absent from oracle grid")
        oracle_output[str(stage)] = {
            "oracle_reproduction": independent_summary(oracles[stage]),
            "selected_regret": independent_summary(np.maximum(regret, 0)),
            "selected_regret_raw_min": float(regret.min()),
        }
    transitions = {}
    for left, right in ((1, 2), (2, 4), (1, 4)):
        delta = trajectory_reproduction[:, right - 1] - trajectory_reproduction[:, left - 1]
        transitions[f"{left}_to_{right}"] = {
            "mean_true_delta": float(delta.mean()),
            "true_error_worsened": int(np.sum(delta > 1e-6)),
            "true_error_worsened_fraction": float(np.mean(delta > 1e-6)),
            "true_error_improved": int(np.sum(delta < -1e-6)),
            "predicted_risk_increased": int(
                np.sum(arrays["trajectory_risk"][:, right - 1] > arrays["trajectory_risk"][:, left - 1] + 1e-5)
            ),
        }
        reported = metrics["refinement"][f"{left}_to_{right}"]
        for key in ("mean_true_delta", "true_error_worsened", "true_error_improved", "predicted_risk_increased"):
            close(transitions[f"{left}_to_{right}"][key], reported[key], f"{label}.refinement.{left}_to_{right}.{key}")
    for i, image_id in enumerate(ids):
        per_image.append({
            "id": image_id,
            "direct_point_reproduction": float(point_reproduction[i]),
            "stage_reproduction": {str(s): float(trajectory_reproduction[i, s - 1]) for s in STAGES},
            "stage_recovery": {str(s): float(trajectory_recovery[i, s - 1]) for s in STAGES},
            "stage_raw_risk": {str(s): float(arrays["trajectory_risk"][i, s - 1]) for s in STAGES},
            "oracle_reproduction": {str(s): float(oracles[s][i]) for s in STAGES},
            "selected_regret": {str(s): float(trajectory_reproduction[i, s - 1] - oracles[s][i]) for s in STAGES},
        })
    return {
        "direct_point": {"reproduction": independent_summary(point_reproduction), "recovery": independent_summary(point_recovery)},
        "stages": stage_summaries,
        "risk_curves": risk_curves,
        "oracle": oracle_output,
        "refinement": transitions,
        "per_image": per_image,
    }


def audit_manifest(run, manifest):
    entries = manifest.get("sha256")
    require(isinstance(entries, dict) and entries, f"{run.name}: malformed artifact manifest")
    required = set(ARCHIVE_FILES) - {"artifact_manifest.json"}
    required |= {"best.pt", "best_point.pt", "last.pt"}
    require(required <= set(entries), f"{run.name}: manifest omits required run evidence")
    for name, expected in entries.items():
        path = run / name
        require(path.is_file(), f"{run.name}: manifested file missing: {name}")
        require(sha256(path) == expected, f"{run.name}: artifact hash mismatch: {name}")


